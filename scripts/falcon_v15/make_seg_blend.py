"""Derive the SAM3 segmentation blend from the Falcon Perception v1.5 blend.

Keeps every `blend_epochized` entry whose subflavor task is
`referring_segmentation` (the grounding sources and the domain ref-seg sets),
with the same repetitions, and drops the rest (image exemplars, OmniCorpus,
cc_math). Subflavors are reduced to `task` (the SAM3 encoder reads only
referring_segmentation objects; `tasks: all` would mean nothing to it).

    python scripts/falcon_v15/make_seg_blend.py \
        ../torchtitan-internal/infra/config/training/datasets/perception_v15.yaml \
        sam3/train/configs/falcon_v15/datasets/sam3_falcon_v15_seg.yaml
"""

import sys

import yaml


def _name(path: str) -> str:
    parts = path.rstrip("/").split("/")
    return parts[-2] if parts[-1] == "tars" else parts[-1]


def main(src: str, dst: str) -> None:
    with open(src) as f:
        blend = yaml.safe_load(f)
    entries = blend["splits"]["train"]["blend_epochized"]
    kept, dropped = [], []
    for e in entries:
        task = (e.get("subflavors") or {}).get("task")
        if task == "referring_segmentation":
            sub = {k: v for k, v in e["subflavors"].items() if k != "tasks"}
            kept.append(
                {"repetitions": e["repetitions"], "path": e["path"], "subflavors": sub}
            )
        else:
            dropped.append(e["path"])
    out = {
        "__module__": blend["__module__"],
        "__class__": blend["__class__"],
        "splits": {"train": {"blend_epochized": kept}},
    }
    header = (
        f"# SAM3 segmentation blend, generated by scripts/falcon_v15/make_seg_blend.py from\n"
        f"# {src.split('torchtitan-internal/')[-1]} ({len(kept)} of {len(entries)} sources kept).\n"
        "# Repetitions are unchanged, so the domain ref-seg sets get a larger share than in v1.5\n"
        "# (the knowledge sources they were balanced against are gone).\n"
        "# Dropped: " + ", ".join(_name(p) for p in dropped) + "\n"
    )
    with open(dst, "w") as f:
        f.write(header)
        yaml.safe_dump(out, f, sort_keys=False, width=120)
    print(f"kept {len(kept)}, dropped {len(dropped)}: {dropped}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
